"""Benchmark the POST82 linear Kalman filter against Dynare.

The native runner times both ``KalmanFilter.run(..., _store_history=False)``
and ``FirstOrderSolvedModel.kalman``. The Dynare runner initializes the model
once with ``dynare`` and then times both Dynare's ``kalman_filter`` likelihood
entry and its generated ``calib_smoother`` entry. Parsing, compilation,
solution, data generation, and warmup are outside the timed repetitions for
both runtimes.

The input panel is generated once through SymbolicDSGE's public simulation API
and written as a Dynare data file.  It is an input artifact, not part of either
timed kernel.  Every runtime therefore filters identical observations.

Usage:
    uv run python scripts/bench_post82_linear_kf.py --runtimes native
    uv run python scripts/bench_post82_linear_kf.py --runtimes native matlab octave \
        --dynare-matlab-path C:/dynare/7.1/matlab

Use ``--matlab-bin`` or ``--octave-bin`` when the executables do not have their
usual names. Each Dynare runtime writes its own inner timings, so process
startup is not included in the warm runtime comparison. Dynare runs in a
temporary benchmark-owned work directory that is removed after each runtime.
Pass ``--output-dir`` to retain the raw benchmark outputs. Otherwise, they are
written to a temporary directory and discarded after reporting.
"""

from __future__ import annotations

import argparse
from contextlib import nullcontext
import json
import shutil
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy.io import loadmat
from scipy.linalg import solve_discrete_lyapunov

ROOT = Path(__file__).resolve().parents[1]
SCRIPT_DIR = Path(__file__).resolve().parent
FIXTURES = ROOT / "tests" / "fixtures" / "models"
MODEL = FIXTURES / "POST82.yaml"
DYNARE_MODEL = FIXTURES / "post82_kf.mod"
OBSERVABLES = ["OutGap", "Infl", "Rate"]
SHOCK_NAMES = ["e_g", "e_z", "e_r"]

sys.path.insert(0, str(ROOT))
from SymbolicDSGE import DSGESolver, ModelParser, SolvedModel
from SymbolicDSGE.estimation import backend
from SymbolicDSGE.kalman.filter import KalmanFilter, FilterResult


def _quoted_matlab(value: Path | str) -> str:
    """Return a MATLAB or Octave single quoted path literal."""
    return str(value).replace("\\", "/").replace("'", "''")


def _max_abs(left: np.ndarray | float, right: np.ndarray | float) -> float:
    return float(np.max(np.abs(np.asarray(left) - np.asarray(right))))


@dataclass
class NativeCase:
    solved: SolvedModel
    A: np.ndarray
    B: np.ndarray
    C: np.ndarray
    d: np.ndarray
    Q: np.ndarray
    R: np.ndarray
    y: np.ndarray
    P0: np.ndarray


def _prepare(periods: int) -> NativeCase:
    """Build the solved model, deterministic panel, and stationary covariance."""
    model, kalman = ModelParser(MODEL).get_all()
    solver = DSGESolver(model, kalman)
    compiled = solver.compile()
    solved = solver.solve(compiled=compiled, order=1)

    base = np.array(
        [
            [0.25, -0.10, 0.40],
            [-0.70, 0.55, -0.15],
            [0.10, 0.20, 0.00],
            [0.60, -0.35, 0.25],
            [-0.20, 0.05, -0.50],
            [0.00, 0.30, 0.10],
            [0.35, -0.45, 0.20],
            [-0.45, 0.15, -0.30],
            [0.15, 0.60, 0.05],
            [-0.10, -0.25, 0.35],
            [0.05, 0.40, -0.20],
            [0.20, -0.05, 0.15],
        ],
        dtype=np.float64,
    )
    shocks = np.resize(base, (periods, len(SHOCK_NAMES)))
    sim = solved.sim(
        T=periods,
        shocks={name: shocks[:, i] for i, name in enumerate(SHOCK_NAMES)},
        observables=True,
    )
    y = np.column_stack(
        [np.asarray(sim.observables[name], dtype=np.float64) for name in OBSERVABLES]
    )
    base_params = backend.extract_base_params(compiled)
    Q = np.asarray(backend.build_Q(compiled, base_params), dtype=np.float64)
    A = np.asarray(solved.policy.A, dtype=np.float64)
    B = np.asarray(solved.policy.B, dtype=np.float64)
    P0 = solve_discrete_lyapunov(A, B @ Q @ B.T)
    P0 = 0.5 * (P0 + P0.T)
    C, d = compiled.build_affine_measurement_matrices(
        base_params, OBSERVABLES, np.asarray(solved.policy.steady_state)
    )
    R = backend.build_R(compiled, kalman, OBSERVABLES, base_params)
    return NativeCase(
        solved=solved,
        A=A,
        B=B,
        C=C,
        d=d,
        Q=Q,
        R=R,
        y=y,
        P0=P0,
    )


def _write_dynare_data(y_values: np.ndarray, path: Path) -> None:
    """Write the ``datafile`` script named by ``post82_kf.mod``."""
    lines = ["% Generated by bench_post82_linear_kf.py. Do not edit."]
    for column, name in enumerate(OBSERVABLES):
        values = "\n".join(f"{value:.17g}" for value in y_values[:, column])
        lines.extend((f"{name} = [", values, "];"))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _time(fn, warmup: int, reps: int) -> tuple[np.ndarray, FilterResult]:
    for _ in range(warmup):
        fn()
    times = np.empty(reps, dtype=np.float64)
    result = None
    for i in range(reps):
        started = time.perf_counter()
        result = fn()
        times[i] = time.perf_counter() - started
    assert result is not None
    return times, result


def _time_native(case: NativeCase, warmup: int, reps: int) -> dict:
    def loglik_only() -> FilterResult:
        return KalmanFilter.run(
            case.A,
            case.B,
            case.C,
            case.d,
            case.Q,
            case.R,
            case.y,
            P0=case.P0,
            _store_history=False,
        )

    def filter_history():
        return case.solved.kalman(
            case.y,
            filter_mode="linear",
            observables=OBSERVABLES,
            P0=case.P0,
        )

    loglik_times, loglik_result = _time(loglik_only, warmup, reps)
    history_times, history_result = _time(filter_history, warmup, reps)
    return {
        "loglik_times": loglik_times,
        "history_times": history_times,
        "loglik": float(loglik_result.loglik),
        "x_pred": np.asarray(history_result.x_pred, dtype=np.float64),
        "x_filt": np.asarray(history_result.x_filt, dtype=np.float64),
    }


def _save_native(result: dict, output_dir: Path) -> None:
    np.savez(output_dir / "native.npz", **result)
    metadata = {
        "runtime": "SymbolicDSGE native",
        "loglik_only_entry_point": "KalmanFilter.run(_store_history=False)",
        "filter_history_entry_point": "FirstOrderSolvedModel.kalman",
        "repetitions": int(result["loglik_times"].size),
        "loglik_only_median_seconds": float(np.median(result["loglik_times"])),
        "filter_history_median_seconds": float(np.median(result["history_times"])),
        "loglik": result["loglik"],
    }
    (output_dir / "native.json").write_text(json.dumps(metadata, indent=2) + "\n")


def _run_dynare(
    runtime: str,
    output_dir: Path,
    y_values: np.ndarray,
    warmup: int,
    reps: int,
    dynare_matlab_path: str,
    matlab_bin: str,
    octave_bin: str,
) -> Path:
    dynare_root = Path(dynare_matlab_path).resolve().parent
    mex_platform = "matlab" if runtime == "matlab" else "octave"
    mex_root = dynare_root / "mex" / mex_platform
    if not mex_root.is_dir():
        raise RuntimeError(
            f"Dynare at {dynare_root} has no {mex_platform} MEX directory. "
            f"Install the Dynare build for {runtime} before benchmarking it."
        )
    runner = SCRIPT_DIR / "bench_post82_linear_kf_dynare.m"
    result_path = output_dir / f"dynare_{runtime}.mat"
    with tempfile.TemporaryDirectory(
        prefix=f"dynare-{runtime}-", dir=output_dir
    ) as temporary_dir:
        workdir = Path(temporary_dir)
        shutil.copy2(DYNARE_MODEL, workdir / DYNARE_MODEL.name)
        _write_dynare_data(y_values, workdir / "post82_kf_data.m")
        expression = (
            f"addpath('{_quoted_matlab(dynare_matlab_path)}'); "
            f"addpath('{_quoted_matlab(runner.parent)}'); "
            f"bench_post82_linear_kf_dynare('{_quoted_matlab(workdir)}', "
            f"{warmup}, {reps}, '{_quoted_matlab(result_path)}');"
        )
        if runtime == "matlab":
            command = [matlab_bin, "-batch", expression]
        else:
            command = [octave_bin, "--quiet", "--eval", expression]
        subprocess.run(command, check=True, cwd=SCRIPT_DIR, stdout=subprocess.DEVNULL)
    return result_path


def _report_dynare(result_path: Path, native: dict) -> dict:
    raw = loadmat(result_path, squeeze_me=True)
    likelihood_times = np.asarray(raw["likelihood_times"], dtype=np.float64).reshape(-1)
    smoother_times = np.asarray(raw["smoother_times"], dtype=np.float64).reshape(-1)
    dynare_loglik = float(np.asarray(raw["loglik"]).squeeze())
    updated = np.asarray(raw["updated"], dtype=np.float64)
    filtered = np.asarray(raw["filtered"], dtype=np.float64)
    report = {
        "likelihood_median_seconds": float(np.median(likelihood_times)),
        "smoother_median_seconds": float(np.median(smoother_times)),
        "repetitions": int(likelihood_times.size),
        "max_abs_loglik": _max_abs(native["loglik"], dynare_loglik),
        "max_abs_updated": _max_abs(native["x_filt"], updated),
        "max_abs_filtered": _max_abs(native["x_pred"][1:], filtered[:-1]),
    }
    return report


def _us(seconds: float) -> str:
    return f"{seconds * 1e6:12.2f}"


def _print_tables(args, native: dict, reports: dict[str, dict]) -> None:
    loglik_median = float(np.median(native["loglik_times"]))
    history_median = float(np.median(native["history_times"]))
    print(
        f"POST82 linear KF: periods={args.periods} warmup={args.warmup} "
        f"reps={args.reps}\n"
        "Setup is outside the timer: parse, compile or preprocess, solve, "
        "input generation, and warmup. Times are microseconds per call.\n"
    )

    print("Loglikelihood Only:")
    loglik_header = (
        f"{'runtime':<39} {'median':>12} {'speedup':>10} {'max |delta loglik|':>20}"
    )
    print(loglik_header)
    print("-" * len(loglik_header))
    print(
        f"{'SymbolicDSGE-loglikonly':<39} {_us(loglik_median)} "
        f"{'1.00x':>10} {'0.000e+00':>20}"
    )
    for runtime, report in reports.items():
        median = report["likelihood_median_seconds"]
        print(
            f"{'Dynare-' + runtime + '-loglikonly':<39} {_us(median)} "
            f"{median / loglik_median:9.2f}x {report['max_abs_loglik']:20.3e}"
        )

    print("\nRetained Results:")
    print(
        "SymbolicDSGE retains FilterResult histories. Dynare's closest public "
        "alternative is calib_smoother, which also computes smoothed paths; "
        "this table is informative but not an equivalent workload."
    )
    history_header = (
        f"{'runtime':<39} {'median':>12} {'speedup':>10} "
        f"{'max |delta updated|':>20} {'max |delta filtered|':>21}"
    )
    print(history_header)
    print("-" * len(history_header))
    print(
        f"{'SymbolicDSGE-filterhistory':<39} {_us(history_median)} "
        f"{'1.00x':>10} {'0.000e+00':>20} {'0.000e+00':>21}"
    )
    for runtime, report in reports.items():
        median = report["smoother_median_seconds"]
        print(
            f"{'Dynare-' + runtime + '-smoother':<39} {_us(median)} "
            f"{median / history_median:9.2f}x "
            f"{report['max_abs_updated']:20.3e} {report['max_abs_filtered']:21.3e}"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--periods", type=int, default=120)
    parser.add_argument("--warmup", type=int, default=3)
    parser.add_argument("--reps", type=int, default=30)
    parser.add_argument(
        "--runtimes",
        nargs="+",
        choices=["native", "matlab", "octave"],
        default=["native"],
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        help="Directory in which to retain raw benchmark outputs, relative to scripts/.",
    )
    parser.add_argument("--dynare-matlab-path", default="")
    parser.add_argument("--matlab-bin", default="matlab")
    parser.add_argument("--octave-bin", default="octave-cli")
    args = parser.parse_args()
    if args.periods < 1 or args.warmup < 0 or args.reps < 1:
        parser.error(
            "periods and reps must be positive, and warmup must be nonnegative"
        )
    if set(args.runtimes) - {"native"} and not args.dynare_matlab_path:
        parser.error("--dynare-matlab-path is required for Dynare runtimes")

    output_context = (
        nullcontext(
            args.output_dir.resolve()
            if args.output_dir.is_absolute()
            else (SCRIPT_DIR / args.output_dir).resolve()
        )
        if args.output_dir is not None
        else tempfile.TemporaryDirectory(prefix="symbolicdsge-post82-linear-kf-")
    )
    with output_context as output_path:
        output_dir = Path(output_path)
        output_dir.mkdir(parents=True, exist_ok=True)

        native_case = _prepare(args.periods)
        native = _time_native(native_case, args.warmup, args.reps)
        _save_native(native, output_dir)

        reports: dict[str, dict] = {}
        for runtime in (name for name in args.runtimes if name != "native"):
            result_path = _run_dynare(
                runtime,
                output_dir,
                native_case.y,
                args.warmup,
                args.reps,
                args.dynare_matlab_path,
                args.matlab_bin,
                args.octave_bin,
            )
            report = _report_dynare(result_path, native)
            reports[runtime] = report

        _print_tables(args, native, reports)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
