import numpy as np
from numpy.typing import NDArray

ROOT = Path(__file__).resolve().parents[1]
SCRIPT_DIR = Path(__file__).resolve().parent
MODEL_FIXTURES = ROOT / "tests" / "fixtures" / "models"
DYNARE_FIXTURES = ROOT / "tests" / "fixtures" / "dynare"
sys.path.insert(0, str(ROOT))

from SymbolicDSGE import (  # noqa: E402
    ModelConfig,
    Shock,
    SolvedModel,
    parse_config,
    solve_model,
)

T = TypeVar("T")
NDF = NDArray[np.float64]


@dataclass(frozen=True)
class Case:
    label: str
    model: str
    seed: int
    observable_map: tuple[tuple[str, str], ...] = ()

    @property
    def yaml_path(self) -> Path:
        return MODEL_FIXTURES / f"{self.model}.yaml"

    @property
    def mod_path(self) -> Path:
        return DYNARE_FIXTURES / f"{self.model}.mod"


CASES = {
    "ls2004": Case("Lubik-Schorfheide 2004", "ls2004", seed=1982),
    "sw2007": Case("SW2007", "sw2007", seed=2007),
    "g2015": Case(
        "Gali 2015",
        "gali_2015",
        seed=2015,
        observable_map=(("obs_pi_ann", "pi_ann"), ("obs_i_ann", "i_ann")),
    ),
    "gm2005": Case(
        "Gali-Monacelli 2005",
        "gali_monacelli_2005",
        seed=2005,
        observable_map=(("obs_pi", "pi"), ("obs_r", "r")),
    ),
    "i2004": Case(
        "Ireland 2004",
        "ireland_2004",
        seed=2004,
        observable_map=(("obs_gobs", "gobs"), ("obs_piobs", "piobs")),
    ),
}


def check_case_table(name: str, table: dict[str, object], *, total: bool) -> None:
    """Fail at import when a bench's own table names a case the shared one lacks."""
    unknown = set(table) - set(CASES)
    missing = set(CASES) - set(table) if total else set()
    if unknown or missing:
        raise RuntimeError(
            f"{name} is out of step with CASES: unknown {sorted(unknown)}, "
            f"missing {sorted(missing)}."
        )


@dataclass
class Prepared:
    config: ModelConfig
    solved: SolvedModel
    y: NDF
    observable_names: tuple[str, ...]


def prepare(case: Case, periods: int) -> Prepared:
    """Solve the case's model and simulate the observations both sides read."""
    config = parse_config(case.yaml_path)
    solved = solve_model(config)
    sim = solved.sim(
        T=periods,
        shocks=[Shock("norm", case.seed).joint(*solved.compiled.shock_names)],
        observables=True,
    )
    if sim.y is None:
        raise RuntimeError("Simulation did not return observables.")
    return Prepared(
        config=config,
        solved=solved,
        y=np.asarray(sim.y, dtype=np.float64),
        observable_names=tuple(sim.observable_names),
    )


def dynare_observable_names(case: Case, names: tuple[str, ...]) -> tuple[str, ...]:
    observable_map = dict(case.observable_map)
    return tuple(observable_map.get(name, name) for name in names)


def write_dynare_data(names: tuple[str, ...], y: NDF, path: Path) -> None:
    lines = ["% Generated by a SymbolicDSGE benchmark. Do not edit."]
    for column, name in enumerate(names):
        lines.extend((f"{name} = [", *(f"{v:.17g}" for v in y[:, column]), "];"))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def quoted_matlab(value: Path | str) -> str:
    return str(value).replace("\\", "/").replace("'", "''")


def time_calls(fn: Callable[[], T], warmup: int, reps: int) -> tuple[NDF, T]:
    for _ in range(warmup):
        fn()
    times = np.empty(reps, dtype=np.float64)
    result: T | None = None
    for i in range(reps):
        started = time.perf_counter()
        result = fn()
        times[i] = time.perf_counter() - started
    assert result is not None
    return times, result


def run_dynare(
    runtime: str, expression: str, args: argparse.Namespace, label: str
) -> None:
    """Run one Dynare driver call under MATLAB or Octave, raising with its stderr."""
    root = Path(args.dynare_matlab_path).resolve().parent
    platform = "matlab" if runtime == "matlab" else "octave"
    if not (root / "mex" / platform).is_dir():
        raise RuntimeError(f"Dynare at {root} has no {platform} MEX directory.")
    expression = (
        f"addpath('{quoted_matlab(args.dynare_matlab_path)}'); "
        f"addpath('{quoted_matlab(SCRIPT_DIR)}'); " + expression
    )
    command = (
        [args.matlab_bin, "-batch", expression]
        if runtime == "matlab"
        else [args.octave_bin, "--quiet", "--eval", expression]
    )
    completed = subprocess.run(
        command,
        cwd=SCRIPT_DIR,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
        text=True,
    )
    if completed.returncode:
        raise RuntimeError(
            f"Dynare {runtime} failed for {label}:\n{completed.stderr.strip()}"
        )


def add_common_args(parser: argparse.ArgumentParser, *, warmup: int, reps: int) -> None:
    parser.add_argument("--periods", type=int, default=120)
    parser.add_argument("--warmup", type=int, default=warmup)
    parser.add_argument("--reps", type=int, default=reps)
    parser.add_argument(
        "--cases", nargs="+", choices=tuple(CASES), default=tuple(CASES)
    )
    parser.add_argument(
        "--runtimes",
        nargs="+",
        choices=["native", "matlab", "octave"],
        default=["native"],
    )
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--dynare-matlab-path", default="")
    parser.add_argument("--matlab-bin", default="matlab")
    parser.add_argument("--octave-bin", default="octave")


def check_common_args(
    parser: argparse.ArgumentParser, args: argparse.Namespace
) -> None:
    if args.periods < 1 or args.warmup < 0 or args.reps < 1:
        parser.error(
            "periods and reps must be positive, and warmup must be nonnegative"
        )
    if set(args.runtimes) - {"native"} and not args.dynare_matlab_path:
        parser.error("--dynare-matlab-path is required for Dynare runtimes")


def output_root(
    args: argparse.Namespace, prefix: str
) -> AbstractContextManager[str | Path]:
    """The ``--output-dir`` folder, or a temporary one that is discarded on exit.

    A relative ``--output-dir`` is read from the benchmarks folder.
    """
    if args.output_dir is None:
        return tempfile.TemporaryDirectory(prefix=prefix)
    path = (
        args.output_dir
        if args.output_dir.is_absolute()
        else SCRIPT_DIR / args.output_dir
    )
    return nullcontext(path.resolve())
