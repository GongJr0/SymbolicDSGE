"""Dynare 7.1 OccBin goldens for the one-constraint NK model with a ZLB.

Generated by ``tests/fixtures/models/make_nk_zlb_goldens.m`` after
``dynare nk_zlb_1_constraint.mod noclearall``, transcribed here at ``%.17g``.
That script prints to stdout and writes nothing, so there are no artifacts to
delete. ``tests/fixtures/models/nk_zlb_1_constraint.yaml`` is our twin of the
same model.

Every array below is written at the generator's own ``%.17g``, one row per line,
inside a ``fmt: off`` block. At sixteen columns of 17 significant digits a row
does not fit in a formatted line, and a formatter is not a reason to store the
data differently: the rows stay one-to-one with the generator's output so a
regeneration can be diffed line for line.

Columns are Dynare's declaration order, ``COLUMNS`` below, which our config
declares in the same order. Both paths are in **levels**, not deviations.

Simulation length is 30, ``simul_periods`` on the run. The ``shocks(surprise)``
block is padded with zeros out to the same 30 so that Dynare records a regime
for every date it reports: ``regime_history`` carries one entry per shock
period, not per simulated period, and the shock alone would have given six.

Regime history is Dynare's own run-length encoding, one date per line as
``(regime, regimestart)``. The ``regimestart`` offsets are counted **from the
current date**, so an entry of 1 is that date itself: entry 1 of ``regime`` is
the realized regime and the tail is the converged guess over the expectation
horizon. A one-constraint run stores those two fields unnumbered, because
``occbin.solver`` sends the model to ``solve_one_constraint``; the numbered
``regime1``/``regimestart1`` pairs of the two-constraint goldens come from
``solve_two_constraints``.

The three binding dates carry guesses of ``((1, 0), (1, 4))``, ``((1, 0),
(1, 3))`` and ``((1, 0), (1, 2))``: at date 6 the bound is expected to hold for
three periods and release on the fourth, and each later date expects one period
less. The realized path exits exactly where the first date's guess said it
would, which is what makes this a fixed point rather than a sequence of
revisions.

``r`` is **exactly** ``ZLB`` on those dates, and ``r_an`` exactly zero, because
the binding regime replaces the policy rule with ``r = ZLB`` outright rather
than penalizing a violation.

**These paths are first order.** OccBin solves the linearized model piecewise,
so the model's nonlinear identities do not hold on them: aggregate supply
``y = l/v`` misses by up to 8e-5 here and labor supply ``w = PSI*l^PHI*c`` by
3e-3, both the size of the second-order term at these deviations. The linearized
identities hold to machine precision instead, which is what the transcription
was checked against: linearized aggregate supply is under 3e-16 on all 30 rows.
The identities that are already linear hold outright, ``y = c + g`` and
``g = G_Y*y`` under 4e-16 and the three reporting rows under 5e-14. Anything
comparing our side against a nonlinear simulation of the same model is asking
the wrong question and will sit at 1e-3.

Two properties of this fixture that read as bugs and are not:

Dates 1 to 5 are the steady state to the last bit on both paths. The shock lands
at date 6 and nothing precedes it, so ``PIECEWISE[0]`` is ``YS`` exactly.

``PIECEWISE`` and ``LINEAR`` still differ on dates 9 to 30 (by up to 4e-4) even
though the bound is long since released. Price dispersion ``v`` carries the
history of the binding spell, so the two paths do not rejoin.

Unlike the two-constraint fixture, neither side is handed its steady state:
Dynare solves the ``steady_state_model`` block and we run Newton, and the two
stop within 5e-13 of each other. ``YS`` is therefore not exact and should not be
read as if it were. Against a 50-digit evaluation of the same closed form, ``x2``
here is 75 ulps out and ``x1`` 63, and evaluating that closed form left to right
in float64 lands 64 ulps out on its own, so the error is in the expression rather
than in whoever solves it. The cause is subtractive cancellation in the
denominator ``1 - THETA*bet*pie**(EPSILON-1)``, which is 0.083 while the product
it subtracts is 0.917: rounding in that product comes out ten times larger in the
difference. ``pie_star`` is 7 ulps out and enters linearly. Our Newton stops of
the same order out on ``x2``, 176 ulps on the machine this was transcribed on,
and where it stops moves with the platform's libm: the parity suite's tolerance
is set for that spread rather than for any one measurement of it.

That conditioning is the floor for every comparison against these arrays, along
with the reporting rows: ``r_an`` and ``pie_an`` scale by 400 and ``yhat`` by
100, so a last-bit disagreement on ``r`` arrives here as 2e-13. Every other
column reproduces to 5e-15 or better, which is the number that says the dynamics
agree. Tolerances set from the worst element of the whole array are measuring
``x1``, ``x2`` and the three reporting rows, nothing else.
"""

