"""Dynare first-order goldens for the POST82 New Keynesian model.

Generated by ``tests/fixtures/models/make_post82_first_order_goldens.m`` after
``dynare post82_first_order.mod noclearall``, then transcribed here at ``%.17g``
and the generated artifacts deleted. Regenerate by rerunning that pair; only the
``.mod`` and the ``.m`` are kept in the tree.

Everything here is raw. Unlike ``dynare_rbc_first_order``, no array below has
been re-dated, rescaled, or reordered on the way out of Dynare, and there is no
``SDSGE`` view: the ``.mod`` is written at Dynare's own dating and the yaml is
written the same way. Where the comparison needs our coordinates rather than
these, it is because the two state vectors differ and the map is our side's,
which ``tests/core/test_dynare_post82_parity`` states and applies.

Ordering is Dynare's declaration order ``[g, z, r, x, Pi]`` throughout, shocks
``[e_g, e_z, e_r]``. ``ORDER_VAR`` and ``STATE_VAR`` are the identity here, so
the raw DR-ordered ``ghx``/``ghu`` and the declaration-ordered ones coincide;
both are kept anyway so a reordering bug cannot hide behind a fixture that
happens not to permute.

Paths follow ``simult_``: one period per row of the shock matrix, initial
condition dropped, so row 0 is ``x1`` and carries the first innovation. IRF row 0
is the impact response, matching ``oo_.irfs``. Every path is the same length as
the shock block that drove it.

This model exists to pin ``B``. ``e_r`` enters a Taylor rule carrying ``Pi(t)``
and ``x(t)``, so the impact of ``e_r`` on ``r`` is a fixed point, ``0.3336``, not
one, and ``e_g`` moves ``r`` on impact by ``0.3470`` through the same rule. A
hand-built impact block wrote those two entries as ``1.0`` and ``0.0``, which is
https://github.com/GongJr0/SymbolicDSGE/issues/390.

Nothing here reimplements a Kalman recursion. The likelihoods come from Dynare's
``kalman_filter.m`` called directly, the state paths from Dynare's smoother run
on ``post82_kf.mod``. A golden produced by a second recursion of our own would
only establish that the same loop can be written twice.

Both filters open a period on the update and close it on the transition, so
``a`` is ``a_{t|t-1}`` on entry and ``P0`` is the covariance of the first
observed state on both sides. Any prior therefore agrees, not only the
unconditional one.

Three observables, unit measurement standard deviations, the observation at
``t`` paired to the state at ``t``.
"""

