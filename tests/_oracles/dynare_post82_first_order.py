"""Dynare first-order goldens for the POST82 New Keynesian model.

Generated by ``tests/fixtures/models/make_post82_first_order_goldens.m`` after
``dynare post82_first_order.mod noclearall``, then transcribed here at ``%.17g``
and the generated artifacts deleted. Regenerate by rerunning that pair; only the
``.mod`` and the ``.m`` are kept in the tree.

Everything here is raw. Unlike ``dynare_rbc_first_order``, no array below has
been re-dated, rescaled, or reordered on the way out of Dynare. There is no
``SDSGE`` view and no seeding transform: the ``.mod`` is written at Dynare's own
dating and the yaml is written the same way, so a comparison against these is
``ours == dynare`` with nothing in between.

Ordering is Dynare's declaration order ``[g, z, r, x, Pi]`` throughout, shocks
``[e_g, e_z, e_r]``. ``ORDER_VAR`` and ``STATE_VAR`` are the identity here, so
the raw DR-ordered ``ghx``/``ghu`` and the declaration-ordered ones coincide;
both are kept anyway so a reordering bug cannot hide behind a fixture that
happens not to permute.

Paths follow ``simult_``: one period per row of the shock matrix, initial
condition dropped, so row 0 is ``x1`` and carries the first innovation. IRF row 0
is the impact response, matching ``oo_.irfs``. Every path is the same length as
the shock block that drove it.

This model exists to pin ``B``. ``e_r`` enters a Taylor rule carrying ``Pi(t)``
and ``x(t)``, so the impact of ``e_r`` on ``r`` is a fixed point, ``0.3336``, not
one, and ``e_g`` moves ``r`` on impact by ``0.3470`` through the same rule.
``sdsge_assemble_state_space`` writes those two entries as ``1.0`` and ``0.0``.
See https://github.com/GongJr0/SymbolicDSGE/issues/390.

Filter conventions, recorded both ways rather than chosen:

* ``P0``: ``P0_UNCOND`` is the unconditional covariance (doubling iteration);
  ``P0_FIXED`` is the identity, which is the yaml's own P0.
* the ``n * log(2 * pi)`` term: ``*_CONST`` includes it, ``*_NOCONST`` omits it.
  The gap is ``12 * 3 * 0.5 * log(2 * pi) == 33.0818``, the signature to look for
  if our loglik is off by a constant.

The recursion is predict-then-update, the observation at ``t`` paired to the
state at ``t``, three observables and unit measurement standard deviations.
"""

